export function cercaComune(query: string): ComuneItaliano[] {
  if (!query || query.trim() === '') return LISTA_COMUNI_ITALIANI.slice(0, 20);
  const q = query.toLowerCase().trim();
  return LISTA_COMUNI_ITALIANI.filter(c => 
    c.nome.toLowerCase().includes(q) || 
    c.provincia.toLowerCase().includes(q) ||
    (c.cap && c.cap.includes(q))
  ).slice(0, 30);
}
